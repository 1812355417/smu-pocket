package com.smu.pocket.core

/**
 * 作息时间表（第 1~14 节的起止时刻）。
 *
 * 教务**没有**「每节课几点上」的接口 —— `qssj`/`jssj` 是**每门课**的起止时刻，
 * 不是每节课的。所以这张表只能本地维护，`RealJw` 与 `FakeJw` 共用这一份，避免两处各写一遍后漂移。
 *
 * 1~12 节不是拍脑袋写的，而是用仓库里真实抓包（`timetable_term.json` / `timetable_week11.json`）
 * 的 `ps`/`pe` + `qssj`/`jssj` 反推出来的。每节课 40 分钟，相邻两节之间休息 5 分钟，
 * 大节（上午/下午/晚上）之间休息 20 分钟：
 *
 * ```
 * ps=01 pe=02 → 08:00-09:25      ps=06 pe=08 → 14:30-16:55
 * ps=03 pe=04 → 09:50-11:15      ps=06 pe=09 → 14:30-17:40
 * ps=03 pe=05 → 09:50-12:00      ps=08 pe=09 → 16:15-17:40
 * ps=10 pe=12 → 19:30-21:40
 * ```
 *
 * 第 13、14 节真实抓包里还没出现过，按同样的节奏往后顺延（21:45 / 22:30）。
 * 学校若改了作息，改这一处即可。
 */
object DefaultPeriods {

    val ALL: List<Period> = listOf(
        // 上午
        Period(1, "08:00", "08:40"),
        Period(2, "08:45", "09:25"),
        Period(3, "09:50", "10:30"),
        Period(4, "10:35", "11:15"),
        Period(5, "11:20", "12:00"),
        // 下午
        Period(6, "14:30", "15:10"),
        Period(7, "15:15", "15:55"),
        Period(8, "16:15", "16:55"),
        Period(9, "17:00", "17:40"),
        // 晚上（晚课会一直排到 11~14 节）
        Period(10, "19:30", "20:10"),
        Period(11, "20:15", "20:55"),
        Period(12, "21:00", "21:40"),
        Period(13, "21:45", "22:25"),
        Period(14, "22:30", "23:10"),
    )
}
